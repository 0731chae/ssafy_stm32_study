void HAL_UART_RxCpltCallback(UART_HandleTypeDef *huart)
{
    // 내 Laptop → STM32
    if (huart->Instance == USART2)
    {
        // Enter 입력
        if (pc_rx_data == '\r' || pc_rx_data == '\n')
        {
            if (pc_index > 0)
            {
                uint8_t newline[] = "\r\n";

                // 내 터미널 줄바꿈
                HAL_UART_Transmit(
                    &huart2,
                    newline,
                    sizeof(newline) - 1,
                    HAL_MAX_DELAY
                );

                // 상대 STM32로 전체 메시지 전송
                HAL_UART_Transmit(
                    &huart1,
                    pc_buffer,
                    pc_index,
                    HAL_MAX_DELAY
                );

                HAL_UART_Transmit(
                    &huart1,
                    newline,
                    sizeof(newline) - 1,
                    HAL_MAX_DELAY
                );

                pc_index = 0;
            }
        }
        else
        {
            if (pc_index < BUFFER_SIZE - 1)
            {
                // 첫 글자라면 "My: " 출력
                if (pc_index == 0)
                {
                    uint8_t my_prefix[] = "My: ";

                    HAL_UART_Transmit(
                        &huart2,
                        my_prefix,
                        sizeof(my_prefix) - 1,
                        HAL_MAX_DELAY
                    );
                }

                // 버퍼에 문자 저장
                pc_buffer[pc_index++] = pc_rx_data;

                // 입력한 문자 즉시 Echo
                HAL_UART_Transmit(
                    &huart2,
                    &pc_rx_data,
                    1,
                    HAL_MAX_DELAY
                );
            }
        }

        // 다음 문자 수신 준비
        HAL_UART_Receive_IT(
            &huart2,
            &pc_rx_data,
            1
        );
    }

    // 상대 STM32 → 내 Laptop
    else if (huart->Instance == USART1)
    {
        if (board_rx_data == '\r' || board_rx_data == '\n')
        {
            if (board_index > 0)
            {
                uint8_t other_prefix[] = "Other: ";
                uint8_t newline[] = "\r\n";

                HAL_UART_Transmit(
                    &huart2,
                    other_prefix,
                    sizeof(other_prefix) - 1,
                    HAL_MAX_DELAY
                );

                HAL_UART_Transmit(
                    &huart2,
                    board_buffer,
                    board_index,
                    HAL_MAX_DELAY
                );

                HAL_UART_Transmit(
                    &huart2,
                    newline,
                    sizeof(newline) - 1,
                    HAL_MAX_DELAY
                );

                board_index = 0;
            }
        }
        else
        {
            if (board_index < BUFFER_SIZE - 1)
            {
                board_buffer[board_index++] = board_rx_data;
            }
        }

        HAL_UART_Receive_IT(
            &huart1,
            &board_rx_data,
            1
        );
    }
}

