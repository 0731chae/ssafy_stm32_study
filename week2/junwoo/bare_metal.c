int main(void)
{

	// 1. GPIOA Clock Enable
	// STM32에서 주변장치에 항상 Clock이 들어가는 것이 아님
	// GPIOA를 사용하려면 먼저 RCC에서 GPIOA Clock을 활성화 해야함
	// RCC: Reset Clock Controller: 리셋과 클럭을 담당
	RCC->AHB1ENR |= (1 << 0);

	// 2. PA0를 Output Mode로 설정
	// 00 : Input
	// 01 : General Purpose Output
	// 10 : Alternate Function
	// 11 : Analog
	// MODER는 핀당 2bit를 사용(e.g. PA5 -> 11:10): (1 << 10)
	// BSRR은 핀당 1bit라 PA5면 (1 << 5)
	GPIOA->MODER &= ~(3 << 0);	// xxxx xx00
	GPIOA->MODER |= (1 << 0);	// xxxx xx01

	// 3. Push-Pull 설정
	// push-pull은 출력 상태가 0이면 LOW, 1이면 HIGH를 내보내는 옵션
	// open drain은 외부 전원을 사용할 때 사용하는 옵션
	// 일반적으로 MCU의 전원으로 HIGH/LOW를 제어하는 상황이면 push-pull 사용
	GPIOA->OTYPER &= ~(1 << 0);

	// 4. Pull-up / Pull-down 사용 안함
	// 일반적으로 output 에서는 pull-up/pull-down이 비활성화
	// documentation에 output configuration 참고
	GPIOA->PUPDR &= ~(3 << 0);


  while (1)
  {

    /* USER CODE END WHILE */
	  // PA0 HIGH -> LED ON
	  GPIOA->BSRR = (1 << 0);
	  delay();

	  // PA0 LOW -> LED OFF
	  GPIOA->BSRR = (1 << 16);
	  delay();
    /* USER CODE BEGIN 3 */
  }
  /* USER CODE END 3 */
}

