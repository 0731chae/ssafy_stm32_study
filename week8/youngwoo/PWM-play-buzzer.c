void Buzzer_Set_Frequency(uint32_t freq)
{
    if (freq == 0) return;

    // PSC = 83 일 때 타이머 카운터 클록은 1MHz (1,000,000 Hz)
    // ARR = (1,000,000 / freq) - 1
    uint32_t arr_value = (100000 / freq) - 1;

    // 듀티 사이클 50% 설정: CCR = (ARR + 1) / 2
    uint32_t ccr_value = (arr_value + 1) / 2;

    // 타이머 레지스터 값 동적 업데이트 (Preload 레지스터 활용)
    __HAL_TIM_SET_AUTORELOAD(&htim2, arr_value);
    __HAL_TIM_SET_COMPARE(&htim2, TIM_CHANNEL_1, ccr_value);
}

void Buzzer_Stop(void)
{
    __HAL_TIM_SET_COMPARE(&htim2, TIM_CHANNEL_1, 0);
}

